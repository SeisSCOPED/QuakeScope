"""Vendored signal kernels for the slim amplitude imports (pick_workload QS_STARTUP2=v2).

The fused amplitude passes need a handful of obspy.signal and scipy.signal functions. Importing
those packages costs ~0.7-1.5 s per worker (scipy.signal's __init__; obspy.signal's __init__ imports
PPSD and with it matplotlib), which would convoy with the first classify. This module carries
verbatim copies of exactly the functions the passes call, so neither package is executed:

* obspy 1.5.1 (LGPL-3.0, obspy.signal.invsim / obspy.signal.util): cosine_taper,
  cosine_sac_taper, waterlevel, invert_spectrum, paz_to_freq_resp, next_pow_2, _npts2nfft.
* scipy 1.18.1 (BSD-3-Clause, scipy.signal._signaltools / _filter_design / _polyutils):
  sosfilt, _validate_x, _validate_sos, zpk2tf, freqs, poly, polyval, with the array namespace
  fixed to numpy.
  The sosfilt kernel is scipy's own compiled scipy/signal/_sosfilt extension, loaded from its file
  without executing scipy/signal/__init__.py, and registered under its own name so a later
  `import scipy.signal` (a fallback) reuses it instead of initialising it twice.
* butter_highpass_sos: the order-4 Butterworth highpass SOS that scipy.signal.iirfilter returns
  for the fused pass's corners (0.2 Hz at the listed sampling rates), as exact float64 values.
  Any other corner is a table miss: the caller falls back to scipy.signal, counted.

Generated by progress-artifacts/evidence/h18/gen_vendor.py; edits to the copied bodies:
  - paz_to_freq_resp: 'b, a = scipy.signal.zpk2tf(zeros, poles, scale_fac)' -> 'b, a = zpk2tf(zeros, poles, scale_fac)'
  - paz_to_freq_resp: '_w, h = scipy.signal.freqs(b, a, f * 2 * np.pi)' -> '_w, h = freqs(b, a, f * 2 * np.pi)'
  - sosfilt: 'xp = array_namespace(sos, x, zi)' -> 'xp = np'
  - sosfilt: 'zi = xp_copy(zi, xp=array_namespace(zi))' -> 'zi = np.array(zi, copy=True)'
  - sosfilt: '_sosfilt(sos, x, zi)' -> '_sosfilt_kernel()(sos, x, zi)'
  - _validate_sos: 'sos = xpx.atleast_nd(sos, ndim=2, xp=xp)' -> 'sos = np.atleast_2d(sos)'
  - zpk2tf: 'xp = array_namespace(z, p)' -> 'xp = _np_xp'
  - freqs: 'xp = array_namespace(b, a, worN)' -> 'xp = _np_xp'
"""

