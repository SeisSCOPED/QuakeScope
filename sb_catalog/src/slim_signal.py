class _xpx:
    """scipy._external.array_api_extra.atleast_nd for numpy arrays."""

    @staticmethod
    def atleast_nd(x, *, ndim, xp=None):
        x = np.asarray(x)
        while x.ndim < ndim:
            x = x[None, ...]
        return x


