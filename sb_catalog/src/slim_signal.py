def butter_highpass_sos(wn: float):
    """iirfilter(4, wn, rp=None, rs=None, btype="highpass", ftype="butter", output="sos"),
    from the table; None for a corner the table does not hold."""
    rows = BUTTER_HIGHPASS_SOS.get(float(wn).hex())
    return None if rows is None else np.array(rows, dtype=np.float64)


