_kernel_lock = threading.Lock()
_kernel = None


def _sosfilt_kernel():
    """scipy.signal._sosfilt._sosfilt, from the extension file, without scipy.signal's __init__."""
    global _kernel
    if _kernel is None:
        with _kernel_lock:
            if _kernel is None:
                module = sys.modules.get("scipy.signal._sosfilt")
                if module is None:
                    import scipy

                    folder = os.path.join(os.path.dirname(scipy.__file__), "signal")
                    for suffix in importlib.machinery.EXTENSION_SUFFIXES:
                        path = os.path.join(folder, "_sosfilt" + suffix)
                        if os.path.exists(path):
                            break
                    else:
                        raise ImportError(f"no scipy/signal/_sosfilt extension in {folder}")
                    loader = importlib.machinery.ExtensionFileLoader("scipy.signal._sosfilt", path)
                    spec = importlib.util.spec_from_file_location("scipy.signal._sosfilt", path,
                                                                  loader=loader)
                    module = importlib.util.module_from_spec(spec)
                    sys.modules["scipy.signal._sosfilt"] = module
                    try:
                        loader.exec_module(module)
                    except BaseException:
                        sys.modules.pop("scipy.signal._sosfilt", None)
                        raise
                _kernel = module._sosfilt
    return _kernel


def load() -> None:
    """Load the sosfilt kernel now (raises ImportError if it cannot be loaded)."""
    _sosfilt_kernel()


